import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const root='C:/Users/Admin/.t3/local-drafts/p6a-prC/';
const base='16689892b4b448d04cac1a8e398f52e5269e7e53',file='packages/ui/src/EquipmentView.svelte';
const git=args=>execFileSync('git',args,{encoding:'utf8'});
const head=git(['rev-parse','HEAD']).trim(),tree=git(['rev-parse','HEAD^{tree}']).trim();
const before=git(['show',base+':'+file]).replaceAll('\r\n','\n'),after=fs.readFileSync(file,'utf8').replaceAll('\r\n','\n');
const extract=(text,label)=>text.match(new RegExp('<svg role="img" aria-label="'+label+'"[\\s\\S]*?<\\/svg>'))?.[0];
const npc=extract(after,'NPC silhouette'),oldNpc=extract(before,'NPC silhouette');
if(!npc||!oldNpc||after.replace(npc,oldNpc)!==before)throw Error('Change extends beyond NPC SVG');
if(extract(before,'Character silhouette')!==extract(after,'Character silhouette'))throw Error('Player SVG changed');
if(Buffer.byteLength(npc)>=6000||!npc.includes('viewBox="0 0 100 200"'))throw Error('SVG bounds/size');
if(/<(?:image|filter|foreignObject)\b|(?:href|url)\s*[:=(]/i.test(npc))throw Error('Raster/filter/external resource');
if([...npc.matchAll(/#[0-9a-f]{6}/gi)].some(m=>m[0].toLowerCase()!=='#d9c499'))throw Error('Unexpected SVG colour');
if(!after.includes('fill:#756248;opacity:.65'))throw Error('Existing fill/opacity changed');
const paths=git(['diff','--name-only',base,'HEAD']).trim().split('\n');
if(paths.length!==1||paths[0]!==file)throw Error('Trace commit scope differs');
const referenceSha=createHash('sha256').update(fs.readFileSync(root+'owner-npc-silhouette-reference.webp')).digest('hex');
if(referenceSha!=='6cb8a6a5ee9f795e52043e4dbc5d833e292919f03deb9a829af7da0a0a0840a5')throw Error('Reference changed');
const result={HEAD:head,tree,base,UTC:new Date().toISOString(),exit:0,changedFiles:paths,markupBytes:Buffer.byteLength(npc),limitBytes:6000,viewBox:'0 0 100 200',role:'img',ariaLabel:'NPC silhouette',fill:'#756248',opacity:.65,knockout:'#d9c499',raster:false,filters:false,referenceSha256:referenceSha,playerUnchanged:true,allNonNpcMarkupUnchanged:true,testsUnchanged:true};
fs.writeFileSync(root+'silhouette/verification.json',JSON.stringify(result,null,2)+'\n','utf8');
console.log(JSON.stringify(result,null,2));
